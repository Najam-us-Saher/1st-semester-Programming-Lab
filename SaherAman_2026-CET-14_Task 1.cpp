#include<iostream>
using namespace std;
int main()
{
	int num1,num2;
	
	cout<<"Enter the value of num1:"<<endl;
	cin>>num1;
	
	cout<<"Enter the value of num2:"<<endl;
	cin>>num2;
	
	cout<<"Remainder of first number:"<<num1%2<<endl;
	cout<<"Remainder of second number:"<<num2%2<<endl;
	
	cout<<"Average of both numbers:"<<(num1+num2)/2<<endl;
	
	cout<<"Square of first number:"<<num1*num1<<endl;
	cout<<"Square of second number:"<<num2*num2<<endl;
	
	return 0;
}
